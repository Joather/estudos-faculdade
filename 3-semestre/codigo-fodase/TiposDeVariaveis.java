public class TiposDeVariaveis {

    public static void main(String[] args) {
        // Criando as TiposDeVariaveis
        int itens = 50;
        float precoPorItem = 9.99f;
        float custoTotal = itens * precoPorItem;
        char moeda = '$';

        // Imprimindo as TiposDeVariaveis
        System.out.println("Quantidade de itens: " + itens);
        System.out.println("Preço por item: " + precoPorItem + moeda);
        System.out.println("Custo total: " + custoTotal);
    }
}
